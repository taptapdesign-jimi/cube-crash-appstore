#!/usr/bin/env python3
"""Cut the supplied 94-title recording without changing the original. Requires numpy and macOS afconvert."""
import hashlib,json,re,subprocess,sys,tempfile,wave
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets/sound/fail board/voices/fail board title voices.mp3'
DEST=ROOT/'assets/sound/fail board/voices/titles-v1'
SOURCE_SHA='106850eb0444429a8443ec1f7909345c49f2ca5fa0b232f522a88579665e22f8'
RATE=48000

def main():
    assert hashlib.sha256(SOURCE.read_bytes()).hexdigest()==SOURCE_SHA,'New source requires a fresh alignment review'
    swift=ROOT/'native/gameplay-results/NativeResultHeadlines.swift'
    titles=json.loads(re.search(r'static let fail:\[String\]=(\[.*?\])',swift.read_text()).group(1))
    assert len(titles)==94 and not {'You Died!','Miss Click?','You Almost!','Wrong Spot!'} & set(titles)
    with tempfile.TemporaryDirectory(prefix='fail-title-pcm-') as directory:
        decoded=Path(directory)/'source.wav'
        subprocess.run(['afconvert',str(SOURCE),str(decoded),'-f','WAVE','-d','LEI16@48000','-c','1'],check=True)
        with wave.open(str(decoded)) as w:
            x=np.frombuffer(w.readframes(w.getnframes()),dtype='<i2').astype(float)/32768
    hop=240
    rms=np.sqrt(np.mean(x[:len(x)//hop*hop].reshape(-1,hop)**2,axis=1))
    active=np.flatnonzero(rms>10**(-40/20));groups=[];start=previous=int(active[0])
    for frame in active[1:]:
        if (frame-previous)*hop/RATE>.20:
            groups.append((start,previous+1));start=int(frame)
        previous=int(frame)
    groups.append((start,previous+1))
    assert len(groups)==len(titles),'Speech island count differs; review before cutting'
    bounds=[0]+[int((a[1]+b[0])*hop/2) for a,b in zip(groups,groups[1:])]+[len(x)]
    DEST.mkdir(parents=True,exist_ok=True);clips=[]
    for i,title in enumerate(titles):
        a,b=bounds[i:i+2];local=x[a:b];n=len(local)//hop
        power=np.sqrt(np.mean(local[:n*hop].reshape(-1,hop)**2,axis=1))
        speech=np.flatnonzero(power>10**(-48/20))
        lo=max(a,a+int(speech[0])*hop-round(.035*RATE))
        hi=min(b,a+int(speech[-1]+1)*hop+round(.065*RATE))
        clip=x[lo:hi].copy();clip-=clip.mean()
        energy=np.sqrt(np.mean(clip[:len(clip)//hop*hop].reshape(-1,hop)**2,axis=1))
        voiced=energy[energy>max(10**(-38/20),energy.max()*10**(-26/20))]
        gain=min(10**(-15/20)/np.sqrt(np.mean(voiced**2)),10**(-.1/20)/np.max(np.abs(clip)))
        clip*=gain;fade=round(.003*RATE)
        clip[:fade]*=np.linspace(0,1,fade);clip[-fade:]*=np.linspace(1,0,fade)
        pcm=np.rint(clip*32767).clip(-32767,32767).astype('<i2')
        slug=re.sub('[^a-z0-9]+','-',title.lower()).strip('-');dest=DEST/f'{i+1:03}-{slug}.wav'
        with wave.open(str(dest),'wb') as w:
            w.setnchannels(1);w.setsampwidth(2);w.setframerate(RATE);w.writeframes(pcm.tobytes())
        clips.append(dict(index=i,title=title,source=str(dest.relative_to(ROOT)),start=lo/RATE,end=hi/RATE,duration=(hi-lo)/RATE,gainDb=float(20*np.log10(gain)),peakDbFS=float(20*np.log10(np.max(np.abs(pcm.astype(float)))/32768)),dc=float(pcm.astype(float).mean()/32768),sha256=hashlib.sha256(dest.read_bytes()).hexdigest()))
    manifest=dict(original=str(SOURCE.relative_to(ROOT)),originalSha256=SOURCE_SHA,format='48000 Hz mono PCM16 WAV',processing='Original speed/pitch; silent-valley trim with 35ms lead/65ms tail, DC removal, 3ms fades; active RMS -15dBFS (Clean Board -18dBFS plus3dB recipe), peak cap -0.1dBFS',alignment='94 speech islands in exact supplied prompt order, checked against local word-timestamp transcript. Clip20 Nearly checked separately because full-source ASR omitted it. Pronunciation and speaker mix need human acceptance.',clips=clips)
    (ROOT/'docs/audio/fail-board-title-voices-v1.json').write_text(json.dumps(manifest,indent=2,ensure_ascii=False)+'\n')
    lines=['// Generated by scripts/prepare-fail-board-title-voices.py.','enum NativeFailBoardTitleVoice {','    struct Entry {let title:String;let source:String}','    static let entries:[Entry] = [']
    lines += ['        Entry(title:'+json.dumps(c['title'],ensure_ascii=False)+',source:'+json.dumps(c['source'])+'),' for c in clips]
    lines += ['    ]','    static func cue(index:Int)->NativeAudioCue? {','        guard entries.indices.contains(index),NativeResultHeadlines.fail.indices.contains(index),','              entries[index].title==NativeResultHeadlines.fail[index] else{return nil}','        return NativeAudioCue(source:entries[index].source,voice:"native-fail-title",gain:0.9064262964918004)','    }','}']
    (ROOT/'native/gameplay-results/NativeFailBoardTitleVoice.swift').write_text('\n'.join(lines)+'\n')
    assert hashlib.sha256(SOURCE.read_bytes()).hexdigest()==SOURCE_SHA
    subprocess.run([sys.executable,str(ROOT/'scripts/boost-fail-board-title-voices.py')],check=True)
    print(f'PASS {len(clips)} title WAVs; original preserved; no clipped samples')
if __name__=='__main__':main()
