"""Sample the selected original Coconut SMIL at the Native 60Hz atlas cadence.
Development only: writes Swift pose data, never transforms or rewrites artwork.
"""
import bisect, json, math, re, xml.etree.ElementTree as ET
from pathlib import Path
root=Path(__file__).resolve().parents[2]
svg=ET.parse(root/'assets/shop/coconut/coconut.svg').getroot()
identity=(1.,0.,0.,1.,0.,0.)
def multiply(m,n):
 a,b,c,d,x,y=m;A,B,C,D,X,Y=n
 return (a*A+c*B,b*A+d*B,a*C+c*D,b*C+d*D,a*X+c*Y+x,b*X+d*Y+y)
def transform(kind,v):
 if kind=='translate':return (1,0,0,1,v[0],v[1] if len(v)>1 else 0)
 if kind=='scale':return (v[0],0,0,v[1] if len(v)>1 else v[0],0,0)
 if kind=='rotate':
  angle=math.radians(v[0]);m=(math.cos(angle),math.sin(angle),-math.sin(angle),math.cos(angle),0,0)
  return multiply(multiply(transform('translate',v[1:]),m),transform('translate',[-v[1],-v[2]])) if len(v)==3 else m
 raise ValueError(kind)
def numbers(s):return list(map(float,re.findall(r'[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?',s)))
def static(s):
 result=identity
 for kind,args in re.findall(r'(\w+)\(([^)]*)\)',s):result=multiply(result,transform(kind,numbers(args)))
 return result
animations=[e for e in svg.iter() if e.tag.split('}')[-1] in ('animate','animateTransform')]
assert {e.get('dur') for e in animations}=={'2.133333s'}
images=[e for e in svg.iter() if e.tag.split('}')[-1]=='image'];assert len(images)==26
indices={id(e):i for i,e in enumerate(images)}
def sample(e,p):
 times=list(map(float,e.get('keyTimes').split(';')));values=[numbers(x) for x in e.get('values').split(';')]
 assert len(times)==len(values)
 i=min(len(times)-1,max(0,bisect.bisect_right(times,p)-1))
 if e.get('calcMode')=='discrete' or i==len(times)-1:return values[i]
 assert e.get('calcMode','linear')=='linear'
 fraction=(p-times[i])/(times[i+1]-times[i])
 return [a+(b-a)*fraction for a,b in zip(values[i],values[i+1])]
def frame(p):
 result=[]
 def visit(e,parent,opacity):
  tag=e.tag.split('}')[-1];local=static(e.get('transform',''));alpha=float(e.get('opacity','1'))
  for animation in e:
   name=animation.tag.split('}')[-1]
   if name=='animateTransform':
    assert animation.get('additive','replace')=='replace'
    local=transform(animation.get('type'),sample(animation,p))
   elif name=='animate':
    assert animation.get('attributeName')=='opacity';alpha=sample(animation,p)[0]
  matrix=multiply(parent,local);alpha*=opacity
  if alpha<=0:return
  if tag=='image':result.append([indices[id(e)]]+[float(e.get(k,'0')) for k in ('x','y','width','height')]+list(matrix)+[alpha])
  else:
   for child in e:
    if child.tag.split('}')[-1] not in ('animate','animateTransform','title'):visit(child,matrix,alpha)
 visit(svg,identity,1)
 assert 1<=len(result)<=2
 return result
frames=[frame(i/128) for i in range(128)]
header='''// Generated by scripts/qa/generate-native-coconut-plan.py from selected original SMIL.
// 26 unchanged WebP image elements; exact nested transform/opacity samples,60Hz.
nonisolated enum NativeCoconutAtlasPlan {
 static let cycle=2.133333
 static let frames:[[[Double]]] = [
'''
rows=[]
for f in frames:
 rows.append('  '+json.dumps([[round(x,9) for x in layer] for layer in f],separators=(',',':')))
(root/'native/gameplay-ui/NativeCoconutAtlasPlan.swift').write_text(header+',\n'.join(rows)+'\n ]\n}\n')
print('Generated128frames,26images,max2simultaneous image layers; source artwork unchanged')
